def utf8_locale():
    enc = (locale.getpreferredencoding(False) or "").upper().replace("UTF8", "UTF-8")
    return "UTF-8" in enc


def unicode_safe():
    """Can this curses build draw multi-byte characters reliably?"""
    if not utf8_locale():
        return False
    version = getattr(curses, "ncurses_version", None) if curses else None
    # macOS system Python ships ncurses 5.4 (2004), which garbles wide chars on partial redraws
    return version is None or tuple(version)[:1] >= (6,)


def _main():
    ap = argparse.ArgumentParser(
        prog=APP,
        description="Find and clean project build folders (node_modules, target, .venv ...) "
                    "and global developer caches.")
    ap.add_argument("path", nargs="?", default="~",
                    help="where to look for projects (default: your home folder)")
    ap.add_argument("-l", "--list", action="store_true", help="print tables instead of the interactive UI")
    ap.add_argument("--json", action="store_true", help="print results as JSON")
    ap.add_argument("-m", "--min-size", default="0", metavar="SIZE",
                    help="hide items smaller than SIZE, e.g. 50M or 1G")
    group = ap.add_mutually_exclusive_group()
    group.add_argument("-P", "--projects-only", action="store_true", help="skip global caches")
    group.add_argument("-C", "--caches-only", action="store_true", help="skip the project scan")
    ap.add_argument("-w", "--workers", type=int, default=8, help="parallel size calculations (default 8)")
    ap.add_argument("--ascii", action="store_true", help="plain ASCII symbols (auto on old ncurses)")
    ap.add_argument("--unicode", action="store_true", help="force Unicode symbols")
    ap.add_argument("-V", "--version", action="version", version=f"{APP} {__version__}")
    args = ap.parse_args()

    root = os.path.abspath(os.path.expanduser(args.path))
    if not os.path.isdir(root):
        ap.error(f"not a directory: {root}")
    try:
        min_size = parse_size(args.min_size)
    except ValueError:
        ap.error(f"can't understand size: {args.min_size}")

    locale.setlocale(locale.LC_ALL, "")
    plain = args.list or args.json or curses is None or not sys.stdout.isatty()
    if plain:
        use_ascii = args.ascii or not utf8_locale()
    else:
        use_ascii = args.ascii or (not args.unicode and not unicode_safe())
    if use_ascii:
        G.update(ASCII_GLYPHS)

    scanner = Scanner(root, max(1, args.workers),
                      projects=not args.caches_only, caches=not args.projects_only).start()

    if plain:
        sys.exit(run_plain(scanner, min_size, args.json))

    os.environ.setdefault("ESCDELAY", "25")  # snappy Esc key
    holder = {}

    def ui(scr):
        app = App(scr, scanner, min_size)
        holder["app"] = app
        app.run()

    try:
        curses.wrapper(ui)
    except KeyboardInterrupt:
        pass

    final = holder["app"].sc if "app" in holder else scanner
    final.stop()
    if final.freed:
        print(f"Freed {human(final.freed)} across {final.cleaned} item(s). "
              f"Reinstall dependencies in a project whenever you need them again.")


def main():
    try:
        _main()
    except BrokenPipeError:  # e.g. piped into `head`
        try:
            sys.stdout = open(os.devnull, "w")
        except OSError:
            pass
        sys.exit(1)


if __name__ == "__main__":
    main()
