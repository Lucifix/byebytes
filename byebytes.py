def match_rule(name, dirpath, siblings):
    candidates = EXACT_RULES.get(name)
    if candidates is None:
        candidates = [r for r in GLOB_RULES if fnmatch.fnmatchcase(name, r.pattern)]
    for r in candidates:
        if r.inner and not any(os.path.exists(os.path.join(dirpath, name, f)) for f in r.inner):
            continue
        if r.markers and not any(fnmatch.filter(siblings, m) for m in r.markers):
            continue
        return r
    return None


