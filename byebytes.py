def human(n):
    if n is None or n == MEASURING:
        return G["ell"]
    if n == UNKNOWN:
        return "?"
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def parse_size(text):
    s = text.strip().upper().rstrip("B")
    mult = {"K": 1024, "M": 1024 ** 2, "G": 1024 ** 3, "T": 1024 ** 4}
    if s and s[-1] in mult:
        return int(float(s[:-1]) * mult[s[-1]])
    return int(float(s or 0))


def ago(ts):
    if not ts:
        return G["dash"]
    days = (time.time() - ts) / 86400
    if days < 1:
        return "today"
    if days < 30:
        return f"{int(days)}d ago"
    if days < 365:
        return f"{int(days // 30)}mo ago"
    return f"{days / 365:.1f}y ago"


def is_stale(ts):
    return bool(ts) and time.time() - ts > STALE_DAYS * 86400


def tilde(path):
    if path == HOME or path.startswith(HOME + os.sep):
        return "~" + path[len(HOME):]
    return path


def ltrunc(text, width):
    ell = G["ell"]
    if width <= 0:
        return ""
    if len(text) <= width:
        return text
    if width <= len(ell):
        return text[-width:]
    return ell + text[-(width - len(ell)):]


def bar_len(frac, width):
    n = int(round(max(0.0, min(1.0, frac)) * width))
    return max(1, n) if frac > 0 else 0


def dir_size(path, cancel=None):
    """On-disk bytes under path. Symlinks inside are not followed."""
    total = 0
    stack = [path]
    while stack:
        if cancel is not None and cancel.is_set():
            break
        current = stack.pop()
        try:
            with os.scandir(current) as it:
                for entry in it:
                    try:
                        if entry.is_dir(follow_symlinks=False):
                            stack.append(entry.path)
                        else:
                            st = entry.stat(follow_symlinks=False)
                            total += st.st_blocks * 512 if USE_BLOCKS else st.st_size
                    except OSError:
                        pass
        except OSError:
            pass
    return total


def project_mtime(dirpath, filenames, rule):
    best = 0.0
    for f in filenames:
        if f in PROJECT_FILES or (rule.markers and any(fnmatch.fnmatchcase(f, m) for m in rule.markers)):
            try:
                best = max(best, os.stat(os.path.join(dirpath, f)).st_mtime)
            except OSError:
                pass
    if not best:
        try:
            best = os.stat(dirpath).st_mtime
        except OSError:
            pass
    return best


