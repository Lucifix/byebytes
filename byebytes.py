NEVER_DELETE = {os.path.realpath(p) for p in (
    "/", HOME, H("Library"), H("Library", "Caches"), H("Library", "Application Support"),
    H("Library", "Developer"), H(".cache"), H(".config"), H(".local"), XDG_DATA, H("Documents"),
    H("Desktop"), H("Downloads"), H("go"), H(".cargo"), H(".gradle"), H(".npm"), H(".nvm"),
)}


def guard(path):
    real = os.path.realpath(path)
    if real in NEVER_DELETE or len(real.strip(os.sep).split(os.sep)) < 3:
        raise RuntimeError(f"refusing to delete {tilde(path)}")


def _retry_writable(func, path, failed):
    """Make path (and its parent) writable and try again - read-only Go caches etc."""
    try:
        os.chmod(os.path.dirname(path), stat.S_IRWXU)
        if not os.path.islink(path):
            os.chmod(path, stat.S_IRWXU if os.path.isdir(path) else stat.S_IRUSR | stat.S_IWUSR)
        func(path)
    except Exception:  # noqa: BLE001
        failed.append(path)


def remove_tree(path, failed):
    def handler(func, p, _exc):
        _retry_writable(func, p, failed)

    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=handler)
    else:
        shutil.rmtree(path, onerror=handler)


def clear_dir(path, failed):
    """Delete everything inside path, keep the folder itself."""
    try:
        with os.scandir(path) as it:
            children = list(it)
    except OSError as ex:
        failed.append(f"{path} ({ex.strerror})")
        return
    for child in children:
        try:
            if child.is_dir(follow_symlinks=False):
                remove_tree(child.path, failed)
            else:
                os.unlink(child.path)
        except OSError:
            _retry_writable(os.unlink, child.path, failed)


