SI_UNITS = {"B": 1, "KB": 1e3, "MB": 1e6, "GB": 1e9, "TB": 1e12, "PB": 1e15}


def _si_bytes(text):
    total = 0.0
    for num, unit in re.findall(r"([\d.]+)\s*([kKMGTP]?B)\b", text):
        total += float(num) * SI_UNITS[unit.upper()]
    return int(total)


def docker_reclaimable():
    try:
        r = subprocess.run(["docker", "system", "df", "--format", "{{.Reclaimable}}"],
                           capture_output=True, text=True, timeout=15)
    except Exception:  # noqa: BLE001
        return UNKNOWN
    if r.returncode != 0:
        return UNKNOWN
    # lines look like "1.2GB (45%)"; drop the percentage before parsing
    return _si_bytes(re.sub(r"\(.*?\)", "", r.stdout))


def docker_freed(output):
    m = re.search(r"Total reclaimed space:\s*(.+)", output)
    return _si_bytes(m.group(1)) if m else 0


