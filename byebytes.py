class Entry:
    __slots__ = ("key", "tab", "paths", "name", "kind", "safety", "note", "cmd", "action",
                 "mtime", "size", "freed", "status", "selected", "error", "sizer", "parse_freed")

    def __init__(self, tab, paths, name, kind, safety, note, action, cmd=None, mtime=0.0,
                 sizer=None, parse_freed=None):
        self.key = tab + ":" + (paths[0] if paths else name)
        self.tab = tab
        self.paths = paths
        self.name = name
        self.kind = kind
        self.safety = safety
        self.note = note
        self.action = action       # "rmtree" | "clear" | "cmd"
        self.cmd = cmd
        self.mtime = mtime
        self.size = MEASURING
        self.freed = 0
        self.status = ""           # "" | "working" | "done" | "error"
        self.selected = False
        self.error = ""
        self.sizer = sizer
        self.parse_freed = parse_freed

    def measure(self, cancel=None):
        if self.sizer is not None:
            return self.sizer()
        return sum(dir_size(p, cancel) for p in self.paths if os.path.isdir(p))


def node_version_entries():
    active = set()
    try:
        out = subprocess.run(["node", "--version"], capture_output=True, text=True, timeout=5).stdout
        if out.strip():
            active.add(out.strip().lstrip("v"))
    except Exception:  # noqa: BLE001
        pass
    nvm_dir = os.environ.get("NVM_DIR") or H(".nvm")
    default_alias = ""
    try:
        with open(os.path.join(nvm_dir, "alias", "default")) as fh:
            default_alias = fh.read().strip().lstrip("v")
    except OSError:
        pass
    fnm_base = (H("Library", "Application Support", "fnm") if IS_MAC
                else os.path.join(XDG_DATA, "fnm"))
    managers = [
        ("nvm", [os.path.join(nvm_dir, "versions", "node")]),
        ("fnm", [os.path.join(fnm_base, "node-versions"), H(".fnm", "node-versions")]),
        ("volta", [H(".volta", "tools", "image", "node")]),
        ("asdf", [H(".asdf", "installs", "nodejs")]),
        ("mise", [os.path.join(XDG_DATA, "mise", "installs", "node")]),
    ]
    entries = []
    for mgr, bases in managers:
        for base in bases:
            try:
                names = sorted(os.listdir(base))
            except OSError:
                continue
            for name in names:
                path = os.path.join(base, name)
                ver = name.lstrip("v")
                if not ver[:1].isdigit() or os.path.islink(path) or not os.path.isdir(path):
                    continue
                is_default = mgr == "nvm" and default_alias[:1].isdigit() and (
                    ver == default_alias or ver.startswith(default_alias + "."))
                if ver in active or is_default:
                    safety, note = PROTECTED, "Your active / default Node version - kept safe."
                else:
                    safety = REVIEW
                    note = (f"Global npm packages installed under this version go with it. "
                            f"Reinstall with: {mgr} install {ver}")
                entries.append(Entry("caches", [path], f"Node v{ver} ({mgr})", "Node versions",
                                     safety, note, "rmtree"))
    return entries


class Scanner:
    def __init__(self, root, workers=8, projects=True, caches=True):
        self.root = root
        self.workers = workers
        self.want_projects = projects
        self.want_caches = caches
        self.entries = []
        self.lock = threading.Lock()
        self.dirs = 0
        self.walking = projects
        self.done = False
        self.t0 = time.time()
        self.t1 = None
        self.freed = 0
        self.cleaned = 0
        self.active_jobs = 0
        self.cancel = threading.Event()
        self.pool = ThreadPoolExecutor(max_workers=workers)

    def start(self):
        threading.Thread(target=self._run, daemon=True).start()
        return self

    def stop(self):
        self.cancel.set()
        try:
            self.pool.shutdown(wait=False, cancel_futures=True)
        except TypeError:  # Python 3.8
            self.pool.shutdown(wait=False)

    def _add(self, e, futures):
        with self.lock:
            self.entries.append(e)
        futures.append(self.pool.submit(self._measure, e))

    def _measure(self, e):
        e.size = e.measure(self.cancel)

    def _run(self):
        futures = []
        try:
            if self.want_caches:
                self._discover_caches(futures)
            if self.want_projects:
                self._walk(futures)
        finally:
            self.walking = False
            for f in futures:
                try:
                    f.result()
                except Exception:  # noqa: BLE001
                    pass
            self.t1 = time.time()
            self.done = True

    def _discover_caches(self, futures):
        for d in cache_defs():
            if d.cmd_only or d.sizer:
                if not (d.cmd and shutil.which(d.cmd[0])):
                    continue
                if d.needs and not os.path.isdir(d.needs):
                    continue
                paths = []
            else:
                paths = [p for p in d.paths if os.path.isdir(p) and not os.path.islink(p)]
                if not paths:
                    continue
            use_cmd = bool(d.cmd and shutil.which(d.cmd[0]))
            e = Entry("caches", paths, d.name, d.group, d.safety, d.note,
                      "cmd" if use_cmd else "clear", cmd=d.cmd if use_cmd else None,
                      sizer=d.sizer, parse_freed=d.parse_freed)
            self._add(e, futures)
        for e in node_version_entries():
            self._add(e, futures)

    def _walk(self, futures):
        for dirpath, dirnames, filenames in os.walk(self.root, followlinks=False):
            if self.cancel.is_set():
                break
            self.dirs += 1
            siblings = filenames + dirnames
            keep = []
            for d in dirnames:
                full = os.path.join(dirpath, d)
                if full in SKIP_PATHS:
                    continue
                rule = match_rule(d, dirpath, siblings)
                if rule is not None:
                    if not os.path.islink(full):
                        rel = os.path.relpath(full, self.root)
                        e = Entry("projects", [full], rel, rule.kind, rule.safety, rule.hint,
                                  "rmtree", mtime=project_mtime(dirpath, filenames, rule))
                        self._add(e, futures)
                    continue  # never descend into a matched folder
                if d in SKIP_NAMES:
                    continue
                keep.append(d)
            dirnames[:] = keep

    # ── cleaning ──────────────────────────────────────────────
    def clean(self, targets):
        for e in targets:
            e.status = "working"
            e.selected = False
            e.error = ""
        with self.lock:
            self.active_jobs += 1

        def work():
            try:
                for e in targets:
                    self._clean_one(e)
            finally:
                with self.lock:
                    self.active_jobs -= 1

        threading.Thread(target=work, daemon=True).start()

    def _clean_one(self, e):
        before = e.size
        failed = []
        output = ""
        try:
            if e.action == "cmd":
                env = dict(os.environ, HOMEBREW_NO_AUTO_UPDATE="1")
                r = subprocess.run(e.cmd, cwd=HOME, stdin=subprocess.DEVNULL, capture_output=True,
                                   text=True, timeout=3600, env=env)
                output = r.stdout + r.stderr
                if r.returncode != 0:
                    lines = [ln for ln in output.strip().splitlines() if ln.strip()]
                    raise RuntimeError(f"`{' '.join(e.cmd)}` failed: {lines[-1] if lines else r.returncode}")
            else:
                for p in e.paths:
                    guard(p)
                    if e.action == "rmtree":
                        remove_tree(p, failed)
                    else:
                        clear_dir(p, failed)
        except Exception as ex:  # noqa: BLE001
            e.error = str(ex)

        if e.sizer is not None:
            after = e.sizer()
        else:
            after = sum(dir_size(p) for p in e.paths if os.path.isdir(p))
        if e.parse_freed and output:
            freed = e.parse_freed(output)
        elif before >= 0 and after >= 0:
            freed = max(0, before - after)
        else:
            freed = 0
        if e.action != "rmtree" or e.error or failed:
            e.size = after
        with self.lock:
            self.freed += freed
        e.freed = freed
        if failed and not e.error:
            e.error = f"{len(failed)} item(s) couldn't be removed, e.g. {tilde(failed[0])}"
        if e.error:
            e.status = "error"
        else:
            e.status = "done"
            with self.lock:
                self.cleaned += 1


# ════════════════════════════════════════════════════════════════ interactive UI

COL_SIZE, COL_BAR, COL_C3, COL_KIND, COL_NAME = 4, 14, 26, 37, 54
BAR_W, KIND_W = 10, 15


class TabState:
    def __init__(self):
        self.cursor = 0
        self.top = 0
        self.cur_key = None
        self.user_moved = False


class App:
    def __init__(self, scr, scanner, min_size):
        self.scr = scr
        self.sc = scanner
        self.min_size = min_size
        self.tab = "projects" if scanner.want_projects else "caches"
        self.ts = {t: TabState() for t in TABS}
        self.rows = []
        self.all_items = []
        self.sort_i = 0
        self.filter = ""
        self.filtering = False
        self.msg = None
        self.c = {}

    @property
    def st(self):
        return self.ts[self.tab]

    # ── setup ──────────────────────────────────────────────────
    def init_colors(self):
        names = ("accent", "red", "yellow", "green", "magenta", "title",
                 "bar_red", "bar_yellow", "bar_green")
        self.c = {n: 0 for n in names}
        if not curses.has_colors():
            self.c["title"] = curses.A_REVERSE
            return
        curses.start_color()
        bg = -1
        try:
            curses.use_default_colors()
        except curses.error:
            bg = curses.COLOR_BLACK
        spec = [
            ("accent", curses.COLOR_CYAN, bg), ("red", curses.COLOR_RED, bg),
            ("yellow", curses.COLOR_YELLOW, bg), ("green", curses.COLOR_GREEN, bg),
            ("magenta", curses.COLOR_MAGENTA, bg), ("title", curses.COLOR_BLACK, curses.COLOR_CYAN),
            ("bar_red", curses.COLOR_BLACK, curses.COLOR_RED),
            ("bar_yellow", curses.COLOR_BLACK, curses.COLOR_YELLOW),
            ("bar_green", curses.COLOR_BLACK, curses.COLOR_GREEN),
        ]
        for i, (name, fg, b) in enumerate(spec, 1):
            curses.init_pair(i, fg, b)
            self.c[name] = curses.color_pair(i)
        self.c["title"] |= curses.A_BOLD

    def size_attr(self, size):
        if size >= BIG:
            return self.c["red"] | curses.A_BOLD
        if size >= MEDIUM:
            return self.c["yellow"]
        return self.c["green"]

    def bar_attr(self, size):
        key = "bar_red" if size >= BIG else "bar_yellow" if size >= MEDIUM else "bar_green"
        return self.c[key] or curses.A_REVERSE

    # ── data ───────────────────────────────────────────────────
    def visible(self):
        with self.sc.lock:
            items = list(self.sc.entries)
        self.all_items = items
        f = self.filter.lower()
        rows = [
            e for e in items
            if e.tab == self.tab
            and not (0 <= e.size < self.min_size and e.status != "done")
            and (not f or f in e.name.lower() or f in e.kind.lower())
        ]
        mode = SORTS[self.sort_i][0]
        if mode == "size":
            rows.sort(key=lambda e: (e.size == MEASURING, e.size == UNKNOWN, -e.size))
        elif mode == "age":
            rows.sort(key=lambda e: e.mtime or float("inf"))
        elif mode == "name":
            rows.sort(key=lambda e: e.name.lower())
        else:
            rows.sort(key=lambda e: (e.kind.lower(), -e.size))
        return rows

    def sync_cursor(self):
        st, n = self.st, len(self.rows)
        if not n:
            st.cursor = 0
            return
        if not st.user_moved:
            st.cursor = 0
        elif st.cur_key is not None:
            for i, e in enumerate(self.rows):
                if e.key == st.cur_key:
                    st.cursor = i
                    break
        st.cursor = max(0, min(st.cursor, n - 1))
        st.cur_key = self.rows[st.cursor].key

    def current(self):
        return self.rows[self.st.cursor] if self.rows else None

    def move(self, delta):
        if not self.rows:
            return
        st = self.st
        st.user_moved = True
        st.cursor = max(0, min(st.cursor + delta, len(self.rows) - 1))
        st.cur_key = self.rows[st.cursor].key

    def flash(self, text, attr=None, secs=4):
        self.msg = (text, self.c["accent"] if attr is None else attr, time.time() + secs)

    # ── drawing ────────────────────────────────────────────────
    def put(self, y, x, text, attr=0):
        h, w = self.scr.getmaxyx()
        if not (0 <= y < h) or x >= w:
            return x + len(text)
        t = text[: max(0, w - x)]
        try:
            self.scr.addstr(y, x, t, attr)
        except curses.error:
            pass  # writing the bottom-right cell raises; harmless
        return x + len(t)

    def list_height(self):
        return self.scr.getmaxyx()[0] - 5

    def draw(self):
        self.scr.erase()
        h, w = self.scr.getmaxyx()
        if h < 9 or w < 72:
            self.put(0, 0, "Terminal too small - make it at least 72x9")
            self.scr.refresh()
            return
        self.draw_header(w)
        self.draw_list(h, w)
        self.draw_footer(h, w)
        self.scr.refresh()

    def draw_header(self, w):
        sc, items, C = self.sc, self.all_items, self.c
        spin, dot = spinner(), G["dot"]
        dim, bold = curses.A_DIM, curses.A_BOLD

        # line 0: logo, root, status
        measuring = sum(1 for e in items if e.size == MEASURING)
        if sc.walking:
            n_proj = sum(1 for e in items if e.tab == "projects")
            status, sattr = f"{spin} scanning {dot} {sc.dirs:,} dirs {dot} {n_proj} found", C["accent"]
        elif not sc.done:
            status, sattr = f"{spin} measuring {dot} {measuring} left", C["accent"]
        else:
            status, sattr = f"{G['ok']} done in {sc.t1 - sc.t0:.1f}s {dot} {sc.dirs:,} dirs", C["green"]
        if sc.active_jobs:
            status, sattr = f"{spin} cleaning {dot} " + status[2:], C["yellow"]
        x = self.put(0, 0, G["logo"], C["title"])
        room = w - x - len(status) - 4
        if sc.want_projects:
            self.put(0, x + 1, ltrunc(tilde(sc.root), room), bold)
        self.put(0, max(0, w - len(status) - 1), status, sattr)

        # line 1: tabs + selection/freed
        x = 0
        for i, t in enumerate(TABS):
            if t == "projects" and not sc.want_projects or t == "caches" and not sc.want_caches:
                continue
            tab_items = [e for e in items if e.tab == t and e.status != "done"]
            total = sum(max(0, e.size) for e in tab_items)
            label = f" {i + 1} {TAB_LABELS[t]} {human(total)} "
            x = self.put(1, x, label, C["title"] if t == self.tab else dim) + 1
        sel = [e for e in self.rows if e.selected]
        segs = [("Selected ", dim), (human(sum(max(0, e.size) for e in sel)), bold | C["magenta"]),
                (f" ({len(sel)})", dim), ("   Freed ", dim), (human(sc.freed), bold | C["green"])]
        right_len = sum(len(t) for t, _ in segs)
        if x + right_len + 2 < w:
            rx = w - right_len - 1
            for text, attr in segs:
                rx = self.put(1, rx, text, attr)

        # line 2: column headers + sort / filter / position
        c3 = "TOUCHED" if self.tab == "projects" else "CLEANS BY"
        name = "FOLDER" if self.tab == "projects" else "CACHE"
        hdr = (" " * COL_SIZE + "SIZE".rjust(9) + " " + "USAGE".ljust(BAR_W) + "  " + c3.rjust(9)
               + "  " + "KIND".ljust(KIND_W) + "  " + name)
        self.put(2, 0, hdr, dim | bold)
        right = f"sort: {sort_label(self.sort_i)}"
        if self.filter:
            right = f"filter: {self.filter}  " + right
        if self.min_size:
            right = f"{G['ge']} {human(self.min_size)}  " + right
        if self.rows:
            right += f"  {self.st.cursor + 1}/{len(self.rows)}"
        if len(hdr) + len(right) + 3 < w:
            self.put(2, w - len(right) - 1, right, dim)

    def draw_list(self, h, w):
        top_y, lh, rows, st = 3, h - 5, self.rows, self.st
        if not rows:
            if self.filter:
                text = "Nothing matches the filter."
            elif not self.sc.done:
                text = "Looking around" + G["ell"]
            elif self.tab == "projects":
                text = "No project folders found. Clean as a whistle."
            else:
                text = "No known caches found on this machine."
            self.put(top_y + lh // 2, max(0, (w - len(text)) // 2), text, curses.A_DIM)
            return
        if st.cursor < st.top:
            st.top = st.cursor
        if st.cursor >= st.top + lh:
            st.top = st.cursor - lh + 1
        st.top = max(0, min(st.top, max(0, len(rows) - lh)))
        biggest = max((e.size for e in rows if e.size > 0 and e.status != "done"), default=1)
        for i in range(lh):
            idx = st.top + i
            if idx >= len(rows):
                break
            self.draw_row(top_y + i, w, rows[idx], idx == st.cursor, biggest)

    def draw_row(self, y, w, e, is_cur, biggest):
        C, spin = self.c, spinner()
        rev = curses.A_REVERSE | curses.A_BOLD
        dim = curses.A_DIM
        if is_cur:
            self.put(y, 0, " " * (w - 1), rev)

        def a(attr):
            return rev if is_cur else attr

        done = e.status == "done"
        self.put(y, 0, G["cur"] if is_cur else " ", a(C["accent"]))
        if e.safety == PROTECTED:
            mark, mattr = G["lock"], C["red"]
        elif e.selected:
            mark, mattr = G["on"], C["magenta"] | curses.A_BOLD
        else:
            mark, mattr = G["off"], dim
        self.put(y, 2, mark, a(mattr))

        # size
        if done:
            shown = human(e.freed) if e.freed or e.size >= 0 else "?"
            self.put(y, COL_SIZE, shown.rjust(9), a(C["green"]))
        else:
            sattr = dim if e.size < 0 else self.size_attr(e.size)
            self.put(y, COL_SIZE, human(e.size).rjust(9), a(sattr))

        # usage bar / status
        txt = None
        if e.status == "working":
            verb = {"rmtree": "deleting", "clear": "clearing", "cmd": "running"}[e.action]
            txt, at = f"{spin} {verb}", C["yellow"]
        elif done:
            txt, at = f"{G['ok']} freed", C["green"]
        elif e.status == "error":
            txt, at = f"{G['bad']} failed", C["red"]
        elif e.size == MEASURING:
            txt, at = f"{spin} measure", dim
        if txt is not None:
            self.put(y, COL_BAR, txt.ljust(BAR_W)[:BAR_W], a(at))
        elif e.size > 0:
            n = bar_len(e.size / biggest, BAR_W)
            if curses.has_colors():
                self.put(y, COL_BAR, " " * n, self.bar_attr(e.size))
            else:
                self.put(y, COL_BAR, G["bar"] * n, a(0))

        # third column: touched (projects) / method (caches)
        if e.tab == "projects":
            c3 = ago(e.mtime)
            c3attr = C["yellow"] if is_stale(e.mtime) and not done else dim
        else:
            c3 = {"cmd": "command", "clear": "delete", "rmtree": "delete"}[e.action]
            c3attr = C["accent"] if e.action == "cmd" else dim
        self.put(y, COL_C3, c3.rjust(9), a(c3attr))

        # kind
        kattr = C["yellow"] if e.safety == REVIEW else (C["red"] if e.safety == PROTECTED else dim)
        self.put(y, COL_KIND, e.kind[:KIND_W], a(kattr))

        # name
        self.put(y, COL_NAME, ltrunc(e.name, w - COL_NAME - 1), a(dim if done else 0))

    def detail_line(self, e):
        """(text, attr) describing the item under the cursor."""
        C = self.c
        if e.error:
            return f"{G['bad']} {e.error}", C["red"]
        if e.action == "cmd":
            where = "runs: " + " ".join(e.cmd)
        elif len(e.paths) > 1:
            where = f"{tilde(e.paths[0])} +{len(e.paths) - 1} more"
        else:
            where = tilde(e.paths[0]) if e.paths else ""
        label = {SAFE: "", REVIEW: "review: ", PROTECTED: "protected: "}[e.safety]
        how = ("restore: " + e.note) if e.tab == "projects" else e.note
        attr = {SAFE: curses.A_DIM, REVIEW: C["yellow"], PROTECTED: C["red"]}[e.safety]
        return f"{where}  {G['dot']}  {label}{how}", attr

    def draw_footer(self, h, w):
        C = self.c
        if self.msg and self.msg[2] > time.time():
            self.put(h - 2, 1, self.msg[0][: w - 2], self.msg[1])
        else:
            e = self.current()
            if e is not None:
                text, attr = self.detail_line(e)
                self.put(h - 2, 1, text[: w - 2], attr)

        y = h - 1
        if self.filtering:
            x = self.put(y, 0, " / ", C["title"])
            x = self.put(y, x + 1, self.filter + G["caret"], curses.A_BOLD)
            self.put(y, x + 2, f"enter keep {G['dot']} esc clear", curses.A_DIM)
            return
        keys = [("tab", "switch"), (G["keys"], "move"), ("space", "select"), ("a/A", "all"),
                ("d", "clean"), ("o", "reveal"), ("c", "copy"), ("s", "sort"), ("/", "filter"),
                ("r", "rescan"), ("q", "quit")]
        x = 1
        for key, label in keys:
            if x + len(key) + len(label) + 3 >= w:
                break
            x = self.put(y, x, key, C["accent"] | curses.A_BOLD)
            x = self.put(y, x + 1, label, curses.A_DIM) + 2

    def confirm(self, text):
        self.draw()
        h, w = self.scr.getmaxyx()
        attr = self.c["red"] | curses.A_REVERSE | curses.A_BOLD
        self.put(h - 1, 0, " " * (w - 1), attr)
        self.put(h - 1, 1, text[: w - 2], attr)
        self.scr.refresh()
        self.scr.timeout(-1)
        try:
            key = self.scr.get_wch()
        except curses.error:
            key = ""
        finally:
            self.scr.timeout(100)
        return key in ("y", "Y")

    # ── actions ────────────────────────────────────────────────
    def selectable(self, e):
        return e.status in ("", "error") and e.safety != PROTECTED

    def clean(self):
        targets = [e for e in self.rows if e.selected and self.selectable(e)]
        if not targets:
            e = self.current()
            if e is None or e.status in ("working", "done"):
                return
            if e.safety == PROTECTED:
                self.flash(f"{e.name} is protected: {e.note}", self.c["red"])
                return
            targets = [e]
        if any(e.size == MEASURING for e in targets):
            self.flash("Still measuring - give it a moment.", self.c["yellow"])
            return
        total = sum(max(0, e.size) for e in targets)
        n_review = sum(1 for e in targets if e.safety == REVIEW)
        if len(targets) == 1:
            e = targets[0]
            if e.action == "cmd":
                q = f"Run `{' '.join(e.cmd)}` ({human(total)})?"
            elif e.action == "clear":
                q = f"Clear {e.name} ({human(total)})?"
            else:
                q = f"Permanently delete {e.name} ({human(total)})?"
            if e.safety == REVIEW:
                q = "[review] " + q
        else:
            q = f"Clean {len(targets)} items ({human(total)})"
            q += f" - {n_review} marked review!" if n_review else "?"
        if self.confirm(q + "  y / N"):
            self.sc.clean(targets)
            self.flash(f"Cleaning {human(total)}{G['ell']}", self.c["yellow"])
        else:
            self.flash("Cancelled.", curses.A_DIM)

    def select_all(self, include_review):
        allowed = (SAFE, REVIEW) if include_review else (SAFE,)
        cand = [e for e in self.rows if self.selectable(e) and e.safety in allowed]
        if not cand:
            return
        value = not all(e.selected for e in cand)
        for e in cand:
            e.selected = value
        what = "all safe + review" if include_review else "all safe"
        self.flash(f"{'Selected' if value else 'Unselected'} {what} items ({len(cand)})")

    def target_path(self, e):
        if e.paths:
            return e.paths[0]
        return None

    def reveal(self):
        e = self.current()
        p = self.target_path(e) if e else None
        if not p:
            return
        target = p if os.path.exists(p) else os.path.dirname(p)
        try:
            if IS_MAC:
                cmd = ["open", "-R", target]
            elif shutil.which("xdg-open"):
                cmd = ["xdg-open", os.path.dirname(target)]
            else:
                self.flash("No file manager opener found.", self.c["yellow"])
                return
            subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            self.flash(f"Opened {tilde(target)}")
        except Exception as ex:  # noqa: BLE001
            self.flash(f"Couldn't open: {ex}", self.c["red"])

    def copy(self):
        e = self.current()
        if e is None:
            return
        text = self.target_path(e) or " ".join(e.cmd or [])
        for cmd in (["pbcopy"], ["wl-copy"], ["xclip", "-selection", "clipboard"]):
            if shutil.which(cmd[0]):
                subprocess.run(cmd, input=text.encode(), check=False)
                self.flash(f"Copied {tilde(text)}")
                return
        self.flash("No clipboard tool found (pbcopy / wl-copy / xclip).", self.c["yellow"])

    def rescan(self):
        if self.sc.active_jobs:
            self.flash("Wait for cleaning to finish first.", self.c["yellow"])
            return
        old = self.sc
        old.stop()
        self.sc = Scanner(old.root, old.workers, old.want_projects, old.want_caches)
        self.sc.freed, self.sc.cleaned = old.freed, old.cleaned
        self.sc.start()
        self.ts = {t: TabState() for t in TABS}
        self.flash("Rescanning" + G["ell"])

    def switch_tab(self, tab=None):
        avail = [t for t in TABS if (t == "projects" and self.sc.want_projects)
                 or (t == "caches" and self.sc.want_caches)]
        if tab is None:
            tab = avail[(avail.index(self.tab) + 1) % len(avail)]
        if tab in avail:
            self.tab = tab

    # ── input ──────────────────────────────────────────────────
    def on_filter_key(self, k):
        if k in ("\n", "\r", curses.KEY_ENTER):
            self.filtering = False
        elif k == "\x1b":
            self.filter, self.filtering = "", False
        elif k in (curses.KEY_BACKSPACE, "\x7f", "\b"):
            self.filter = self.filter[:-1]
        elif isinstance(k, str) and k.isprintable():
            self.filter += k
        self.st.user_moved = False

    def on_key(self, k):
        lh = self.list_height()
        if k == "\x1b" and self.filter:
            self.filter = ""
        elif k in ("q", "Q", "\x1b"):
            if self.sc.active_jobs and not self.confirm(
                    "Cleaning still running - quit anyway and leave it half done?  y / N"):
                return True
            return False
        elif k in ("\t", curses.KEY_BTAB, curses.KEY_RIGHT, curses.KEY_LEFT):
            self.switch_tab()
        elif k in ("1", "2"):
            self.switch_tab(TABS[int(k) - 1])
        elif k in (curses.KEY_UP, "k"):
            self.move(-1)
        elif k in (curses.KEY_DOWN, "j"):
            self.move(1)
        elif k == curses.KEY_PPAGE:
            self.move(-lh)
        elif k == curses.KEY_NPAGE:
            self.move(lh)
        elif k in (curses.KEY_HOME, "g"):
            self.move(-len(self.rows))
        elif k in (curses.KEY_END, "G"):
            self.move(len(self.rows))
        elif k == " ":
            e = self.current()
            if e is not None and e.safety == PROTECTED:
                self.flash(f"{e.name} is protected: {e.note}", self.c["red"])
            elif e is not None and self.selectable(e):
                e.selected = not e.selected
                self.move(1)
        elif k == "a":
            self.select_all(False)
        elif k == "A":
            self.select_all(True)
        elif k in ("d", "D", "x", curses.KEY_DC):
            self.clean()
        elif k == "o":
            self.reveal()
        elif k == "c":
            self.copy()
        elif k == "s":
            self.sort_i = (self.sort_i + 1) % len(SORTS)
            self.flash(f"Sorted by {sort_label(self.sort_i)}")
        elif k == "/":
            self.filtering = True
        elif k == "r":
            self.rescan()
        return True

    def run(self):
        try:
            curses.curs_set(0)
        except curses.error:
            pass
        self.init_colors()
        self.scr.keypad(True)
        self.scr.timeout(100)
        while True:
            self.rows = self.visible()
            self.sync_cursor()
            self.draw()
            try:
                k = self.scr.get_wch()
            except curses.error:
                continue  # timeout -> redraw (spinner, live results)
            if k == curses.KEY_RESIZE:
                continue
            if self.filtering:
                self.on_filter_key(k)
            elif not self.on_key(k):
                return


