def run_plain(sc, min_size, as_json):
    tty = sys.stderr.isatty()
    try:
        while not sc.done:
            if tty:
                sys.stderr.write(f"\r\033[K{spinner()} scanning {G['dot']} {sc.dirs:,} dirs "
                                 f"{G['dot']} {len(sc.entries)} found")
                sys.stderr.flush()
            time.sleep(0.1)
    except KeyboardInterrupt:
        sc.stop()
        if tty:
            sys.stderr.write("\r\033[K")
        print("Interrupted.", file=sys.stderr)
        return 130
    if tty:
        sys.stderr.write("\r\033[K")
        sys.stderr.flush()

    def keep(e):
        return not (0 <= e.size < min_size)

    def by_size(e):
        return -e.size if e.size >= 0 else 1

    projects = sorted((e for e in sc.entries if e.tab == "projects" and keep(e)), key=by_size)
    caches = sorted((e for e in sc.entries if e.tab == "caches" and keep(e)), key=by_size)

    if as_json:
        out = {
            "projects": [{
                "path": e.paths[0], "kind": e.kind, "safety": e.safety, "bytes": e.size,
                "size": human(e.size), "restore": e.note,
                "last_touched": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(e.mtime)) if e.mtime else None,
            } for e in projects] if sc.want_projects else None,
            "caches": [{
                "name": e.name, "group": e.kind, "safety": e.safety,
                "bytes": e.size if e.size >= 0 else None, "size": human(e.size),
                "paths": e.paths, "command": e.cmd, "note": e.note,
            } for e in caches] if sc.want_caches else None,
        }
        json.dump(out, sys.stdout, indent=2)
        print()
        return 0

    color = sys.stdout.isatty()

    def paint(text, code):
        return f"\033[{code}m{text}\033[0m" if color else text

    def size_code(n):
        return "1;31" if n >= BIG else "33" if n >= MEDIUM else "32"

    def safety_mark(e):
        return {SAFE: " ", REVIEW: paint("?", "33"), PROTECTED: paint("#", "31")}[e.safety]

    if sc.want_projects:
        print(paint(f"PROJECTS  {tilde(sc.root)}", "1;36"))
        if projects:
            print(paint(f"  {'SIZE':>9}  {'TOUCHED':>9}  {'KIND':<15}  FOLDER", "2"))
            for e in projects:
                print(f"{safety_mark(e)} {paint(human(e.size).rjust(9), size_code(e.size))}  "
                      f"{paint(ago(e.mtime).rjust(9), '33' if is_stale(e.mtime) else '2')}  "
                      f"{e.kind:<15}  {tilde(e.paths[0])}")
            total = sum(max(0, e.size) for e in projects)
            print(f"  {len(projects)} folders {G['dot']} {paint(human(total), '1')}")
        else:
            print("  nothing found")
        print()
    if sc.want_caches:
        print(paint("CACHES", "1;36"))
        if caches:
            print(paint(f"  {'SIZE':>9}  {'GROUP':<15}  {'CACHE':<24}  LOCATION / COMMAND", "2"))
            for e in caches:
                where = " ".join(e.cmd) if e.cmd else tilde(e.paths[0]) + (
                    f" +{len(e.paths) - 1}" if len(e.paths) > 1 else "")
                print(f"{safety_mark(e)} {paint(human(e.size).rjust(9), size_code(max(0, e.size)))}  "
                      f"{e.kind:<15}  {e.name:<24}  {paint(where, '2')}")
            total = sum(max(0, e.size) for e in caches)
            print(f"  {len(caches)} caches {G['dot']} {paint(human(total), '1')}")
        else:
            print("  nothing found")
        print()
    print(paint(f"? = review before deleting   # = protected   "
                f"scanned {sc.dirs:,} dirs in {sc.t1 - sc.t0:.1f}s", "2"))
    return 0


